-- Учебное пересоздание таблиц с нуля (удаление в порядке, обратном зависимостям FK)
DROP TABLE IF EXISTS appeals;
DROP TABLE IF EXISTS service_types;
DROP TABLE IF EXISTS users;

-- 1. Справочник категорий академических услуг деканата (3НФ)
CREATE TABLE service_types (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL UNIQUE,
    description text NOT NULL DEFAULT '',
    is_active boolean NOT NULL DEFAULT true
);

-- 2. Пользователи системы (создатели и исполнители обращений)
CREATE TABLE users (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name text NOT NULL,
    email text NOT NULL UNIQUE,
    role text NOT NULL CHECK (role IN ('Student', 'ViceDean', 'Staff')),
    created_at timestamptz NOT NULL DEFAULT now()
);

-- 3. Главный объект — обращения студентов в деканат
CREATE TABLE appeals (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    number text NOT NULL UNIQUE,
    title text NOT NULL CHECK (char_length(btrim(title)) BETWEEN 5 AND 80),
    description text NOT NULL CHECK (char_length(btrim(description)) BETWEEN 10 AND 500),
    service_type_id integer NOT NULL REFERENCES service_types (id),
    status text NOT NULL CHECK (status IN ('New', 'InProgress', 'Closed', 'Cancelled')),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    created_by_user_id integer NOT NULL REFERENCES users (id),
    assignee_user_id integer NULL REFERENCES users (id)
);

-- Индекс ускоряет фильтрацию списка по статусу (WHERE status = 'New') и сводку GROUP BY status
CREATE INDEX appeals_status_idx ON appeals (status);

-- Индекс ускоряет выборку по категории услуги и соединение JOIN с таблицей service_types
CREATE INDEX appeals_service_type_id_idx ON appeals (service_type_id);

-- Индекс ускоряет сортировку обращений по дате создания от новых к старым (ORDER BY created_at DESC)
CREATE INDEX appeals_created_at_idx ON appeals (created_at DESC);
